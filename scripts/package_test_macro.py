#!/usr/bin/env python3
"""Bundle the tested benchmark and dialog launcher into one downloadable FreeCAD macro."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
benchmark = (root / 'benchmarks/techdraw_bench.py').read_text(encoding='utf-8')
launcher = (root / 'benchmarks/interactive_test.py').read_text(encoding='utf-8')
launcher = launcher.replace('from techdraw_bench import Runner\n', '')
for name, arguments in [('TechDrawTest.FCMacro', ''),
                        ('TechDrawSelectionDiagnose.FCMacro', 'selection_diagnostics=True')]:
    output = root / 'benchmarks' / name
    output.write_text(
        '# Generated by scripts/package_test_macro.py; edit the Python sources instead.\n'
        '# Standalone: no extra Python files or packages to install.\n'
        + benchmark + '\n\n' + launcher
        + f'\n\nTECHDRAW_TEST_RUNNER = start_interactive({arguments})\n', encoding='utf-8')
    print(output)
